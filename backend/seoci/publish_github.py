"""Submit approved Astro articles for review, never to the base branch."""
import base64
import json
import re
from datetime import date
from urllib.parse import quote

import httpx
from fastapi import HTTPException

from seoci.api.schemas import PublishingConfig
from seoci.config import settings


def blog_file(draft):
    meta = draft.metadata_json
    title = meta.get("title") or "Untitled article"
    slug = re.sub(r"[^a-z0-9]+", "-", (meta.get("slug") or title).lower()).strip("-") or "article"
    frontmatter = ["---", f"title: {json.dumps(title, ensure_ascii=False)}",
                   f"description: {json.dumps(meta.get('meta_description', ''), ensure_ascii=False)}",
                   f"pubDate: {date.today().isoformat()}"]
    if meta.get("tags"):
        frontmatter.append(f"tags: {json.dumps(meta['tags'], ensure_ascii=False)}")
    return slug, "\n".join([*frontmatter, "---", "", draft.body_md, ""])


def publish(project, run, draft, qa_status, client=None):
    config = PublishingConfig.model_validate(project.publishing or {})
    if not config.github_repo:
        raise HTTPException(400, "Configure github_repo in project publishing settings first")
    if not settings.github_token:
        raise HTTPException(400, "GitHub token is not configured; set GITHUB_TOKEN on the server")
    if client is None:
        with httpx.Client(timeout=settings.network_timeout) as owned:
            return publish(project, run, draft, qa_status, client=owned)

    def request(method, path, **kwargs):
        try:
            response = client.request(method, f"{settings.github_api_url.rstrip('/')}/repos/{config.github_repo}/{path}",
                                      headers={"Authorization": f"Bearer {settings.github_token}",
                                               "Accept": "application/vnd.github+json",
                                               "X-GitHub-Api-Version": "2022-11-28"}, **kwargs)
        except httpx.RequestError:
            raise HTTPException(502, "GitHub could not be reached; please retry") from None
        return response

    def checked(response):
        if response.is_success:
            return response.json()
        messages = {401: "GitHub authentication failed; check the server token",
                    403: "GitHub denied access or rate limited the request; check token permissions",
                    404: "GitHub repository or base branch not found; check repository access and settings",
                    422: "GitHub rejected the branch, file or PR; check settings and existing branches"}
        raise HTTPException(502, messages.get(response.status_code, "GitHub API request failed; please retry"))

    slug, content = blog_file(draft)
    branch = f"seoci/{slug}-{run.id[:8]}"
    path = f"{config.content_dir}/{slug}.{config.file_extension}"
    base = checked(request("GET", f"git/ref/heads/{quote(config.base_branch, safe='')}"))
    existing = request("GET", f"contents/{quote(path, safe='/')}", params={"ref": config.base_branch})
    if existing.is_success:
        raise HTTPException(409, f"File already exists on {config.base_branch}: {path}; choose a different slug")
    if existing.status_code != 404:
        checked(existing)
    checked(request("POST", "git/refs", json={"ref": f"refs/heads/{branch}", "sha": base["object"]["sha"]}))
    checked(request("PUT", f"contents/{quote(path, safe='/')}", json={
        "message": f"Add article: {draft.metadata_json.get('title', slug)}", "branch": branch,
        "content": base64.b64encode(content.encode()).decode()}))
    pr = checked(request("POST", "pulls", json={
        "title": draft.metadata_json.get("title") or slug, "head": branch, "base": config.base_branch,
        "body": f"Keyword: {run.primary_keyword}\n\nRun: {run.id}\n\nQA status: {qa_status}\n\n"
                "Generated by SEO Content Intelligence. Needs human review before merging or publishing."}))
    return {"pr_url": pr["html_url"], "pr_number": pr["number"], "branch": branch, "path": path}
